use std::path::Path;

use crate::sfc::Sfc;

/// Extremely simple stub codegen that emits a Rust module with raw blocks.
/// Later, you'll compile `<template>` into VNodes and `<style>` into native styles.
pub fn to_stub_rs(sfc: &Sfc, component_name: &str) -> String {
    to_stub_rs_inner(sfc, component_name, None, true)
}

/// Same as `to_stub_rs` but accepts an optional base path for import resolution.
/// When provided, relative imports are resolved from this path instead of CWD.
///
/// The output is wrapped in `pub mod {name} { ... }`, suitable for `include!()`
/// in a standalone build script context.
pub fn to_stub_rs_with_base(sfc: &Sfc, component_name: &str, base_path: Option<&Path>) -> String {
    to_stub_rs_inner(sfc, component_name, base_path, true)
}

/// Same as `to_stub_rs_with_base` but emits the module body *without* the
/// `pub mod {name} { ... }` wrapper. Use this when the caller already manages
/// module declarations (e.g., via `#[path]` attributes in a component tree).
pub fn to_stub_rs_unwrapped(sfc: &Sfc, component_name: &str, base_path: Option<&Path>) -> String {
    to_stub_rs_inner(sfc, component_name, base_path, false)
}

fn to_stub_rs_inner(
    sfc: &Sfc,
    component_name: &str,
    base_path: Option<&Path>,
    wrap_module: bool,
) -> String {
    let t = sfc
        .template
        .as_ref()
        .map(|b| b.content.as_str())
        .unwrap_or("");
    let ss = sfc
        .script_setup
        .as_ref()
        .map(|b| b.content.as_str())
        .unwrap_or("");
    let s = sfc
        .script
        .as_ref()
        .map(|b| b.content.as_str())
        .unwrap_or("");
    let st = sfc.style.as_ref().map(|b| b.content.as_str()).unwrap_or("");

    let name = sanitize_ident(component_name);
    let open = "{";
    let close = "}";

    // Create resolver for component imports using the provided base path.
    // If no base path is given, fall back to the current working directory.
    let resolver_base = base_path
        .map(|p| p.to_path_buf())
        .unwrap_or_else(|| std::env::current_dir().unwrap_or_default());
    let mut resolver = crate::component_resolver::ComponentResolver::new(resolver_base);
    if let Some(script_setup) = &sfc.script_setup {
        resolver.parse_imports(&script_setup.content);
    }

    // NOTE: We intentionally do NOT generate `pub mod {name};` declarations here.
    // The caller (e.g., compile_component_tree in velox-cli) is responsible for
    // generating `#[path = "..."] pub mod ...;` declarations with correct file paths.
    // Generating bare `pub mod` here would conflict with the caller's declarations
    // and cause "file not found for module" errors.

    // Check if the template has any component @event listeners to determine
    // if we need emit infrastructure
    let needs_emit_infra = template_needs_emit_infra(sfc);

    // NOTE: Scoped CSS is currently passed through as-is. The CSS parser
    // (`parse_selector_list` in velox-style) supports class, tag, tag.class,
    // and descendant selectors (e.g., `.header h1`). Scoped styles work
    // globally (unscoped) since attribute-scoped selectors are not yet
    // supported.
    // TODO: Implement proper scoped CSS by enhancing the CSS parser to handle
    // attribute selectors and adding scope identifiers to rendered VNodes.
    let processed_style = st.to_string();
    let processed_template = t.to_string();

    // Indent level: 4 spaces when wrapped in a module, 0 when unwrapped.
    let indent = if wrap_module { "    " } else { "" };
    let inner_indent = if wrap_module { "        " } else { "    " };

    // Build output manually to allow embedding script_setup as raw Rust.
    let mut out = String::new();
    out.push_str("// @generated by velox-sfc (stub)\n");
    // Always use outer #[allow] — works at file-level and inside pub mod {} blocks.
    out.push_str("#[allow(clippy::vec_init_then_push)]\n");

    // If any component in the template uses @event, we need the emit module
    if needs_emit_infra {
        out.push_str(&format!("{indent}use std::cell::RefCell;\n"));
        out.push_str(&format!("{indent}use std::collections::HashMap;\n\n"));
        // Emit infrastructure is already indented for module-level (4 spaces).
        // When unwrapped, strip that indentation.
        let emit_code = generate_emit_infrastructure();
        if wrap_module {
            out.push_str(&emit_code);
        } else {
            for line in emit_code.lines() {
                let stripped = line.strip_prefix("    ").unwrap_or(line);
                out.push_str(stripped);
                out.push('\n');
            }
        }
        out.push('\n');
    }

    if wrap_module {
        out.push_str(&format!("pub mod {} {}\n", name, open));
    }
    out.push_str(&format!(
        "{indent}pub const TEMPLATE: &str = r#\"{}\"#;\n",
        escape_raw_string(&processed_template)
    ));
    out.push_str(&format!(
        "{indent}pub const SCRIPT_SETUP: &str = r#\"{}\"#;\n",
        escape_raw_string(ss)
    ));
    out.push_str(&format!(
        "{indent}pub const SCRIPT: &str = r#\"{}\"#;\n",
        escape_raw_string(s)
    ));
    out.push_str(&format!(
        "{indent}pub const STYLE: &str = r#\"{}\"#;\n",
        escape_raw_string(&processed_style)
    ));
    if !ss.is_empty() {
        out.push_str(&format!("{indent}pub mod script_rs {{\n{inner_indent}#![allow(unused_variables, unused_imports, unused_mut, unused_assignments, clippy::new_without_default)]\n"));
        out.push_str(&format!("{inner_indent}use super::*;\n"));

        // If this component itself needs emit infrastructure (parent uses @event on it),
        // add the callback type and emit helper
        if ss.contains("define_emits") || ss.contains("emit(") {
            let helpers = generate_component_emit_helpers();
            // helpers are indented for module-level; adjust for inner_indent
            for line in helpers.lines() {
                // Strip the 8-space prefix that was designed for the wrapped format
                let stripped = line
                    .strip_prefix("        ")
                    .unwrap_or(line.strip_prefix("    ").unwrap_or(line));
                out.push_str(&format!("{inner_indent}{stripped}\n"));
            }
        }

        // Insert user code as-is, BUT skip import lines (e.g., `import X from 'Y.vx'`).
        // Import lines are a Velox DSL, not valid Rust. They are already stored
        // in the SCRIPT_SETUP constant above. The caller handles module declarations
        // for imported components via #[path] attributes.
        for line in ss.lines() {
            if is_import_line(line) {
                continue;
            }
            out.push_str(&format!("{inner_indent}{line}\n"));
        }

        // Generate v-model setter methods on the State struct.
        // Parse the template to find v-model directives, then emit setter methods
        // that the event dispatch system can call (e.g., __vmodel_set_counter).
        if let Some(template_block) = &sfc.template
            && let Ok(template_nodes) =
                crate::template_parse::parse_template_to_ast(&template_block.content)
        {
            let vmodels = crate::template_codegen::collect_vmodel_expressions(&template_nodes);
            if !vmodels.is_empty() {
                let setters = crate::template_codegen::generate_vmodel_setters(&vmodels);
                for line in setters.lines() {
                    out.push_str(&format!("{inner_indent}{line}\n"));
                }
            }
        }

        out.push_str(&format!("{indent}}}\n"));
    }

    // Generate render_with_callbacks if the component has emit declarations
    if ss.contains("define_emits") || ss.contains("emit(") {
        let render_cb = generate_render_with_callbacks_inside_module();
        // The template has 4-space indentation; adjust to indent level
        for line in render_cb.lines() {
            let stripped = line.strip_prefix("    ").unwrap_or(line);
            out.push_str(&format!("{indent}{stripped}\n"));
        }
    }

    if wrap_module {
        out.push_str(close);
        out.push('\n');
    }
    out
}

/// Check if a line is a Velox component import statement.
/// Matches patterns like:
///   import MyButton from './components/Button.vx'
///   import { Button, Card } from './components.vx'
fn is_import_line(line: &str) -> bool {
    let trimmed = line.trim();
    trimmed.starts_with("import ") && trimmed.contains(" from ")
}

/// Check if the template contains component tags with @event listeners.
fn template_needs_emit_infra(sfc: &Sfc) -> bool {
    let template = match &sfc.template {
        Some(t) => &t.content,
        None => return false,
    };
    // Simple heuristic: if template has `@` followed by word and `=` after a component-like tag
    // we check for the pattern `@event="handler"` which indicates parent listening to child
    template.contains("@") && template.contains("=\"")
}

/// Generate the global emit infrastructure: Callbacks type, emit function,
/// and set_callback function using thread-local storage.
fn generate_emit_infrastructure() -> String {
    r#"    /// Type alias for callback maps passed to child components.
    pub type Callbacks = std::collections::HashMap<&'static str, &'static str>;

    // Thread-local callback registry for emit system.
    // Stores event name -> handler function name mappings.
    thread_local! {
        static EMIT_CALLBACKS: RefCell<HashMap<String, String>> = RefCell::new(HashMap::new());
    }

    /// Register callbacks for the current render scope.
    /// Called by `render_with_callbacks` before rendering a child component.
    pub fn set_emit_callbacks(callbacks: &Callbacks) {
        EMIT_CALLBACKS.with(|cell| {
            let mut map = cell.borrow_mut();
            map.clear();
            for (k, v) in callbacks {
                map.insert(k.to_string(), v.to_string());
            }
        });
    }

    /// Emit an event from a child component to its parent.
    /// Looks up the registered callback and returns the handler name.
    /// The caller is responsible for invoking the handler on their State.
    pub fn emit(event: &str, _payload: &str) -> Option<String> {
        EMIT_CALLBACKS.with(|cell| {
            let map = cell.borrow();
            map.get(event).cloned()
        })
    }"#
    .to_string()
}

/// Generate emit helpers that go inside the component's script_rs module.
fn generate_component_emit_helpers() -> String {
    r#"
        /// Emit an event to the parent component's handler.
        /// Looks up the callback name from the thread-local registry.
        pub fn emit(event: &str, payload: &str) {
            if let Some(_handler_name) = super::emit(event, payload) {
                // The handler will be invoked via the parent's on_event dispatcher.
                // The handler_name corresponds to a method on the parent's State.
            }
        }
"#
    .to_string()
}

/// Generate `render_with_callbacks` function that accepts callbacks from a parent.
/// This goes INSIDE the module (before the closing brace).
fn generate_render_with_callbacks_inside_module() -> String {
    r#"
    /// Render this component with callbacks from a parent component.
    /// The callbacks map event names to parent handler method names.
    pub fn render_with_callbacks(
        props: std::collections::HashMap<&str, String>,
        callbacks: &std::collections::HashMap<&'static str, &'static str>,
        _handler_names: &[&'static str],
    ) -> velox_dom::VNode {
        // Register callbacks in thread-local storage so emit() can find them
        super::set_emit_callbacks(callbacks);
        // Render using the standard props path
        render_with_props(props)
    }
"#
    .to_string()
}

fn sanitize_ident(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for (i, ch) in raw.chars().enumerate() {
        if (i == 0 && ch.is_ascii_digit()) || !is_ident_char(ch) {
            out.push('_');
        } else {
            out.push(ch.to_ascii_lowercase());
        }
    }
    if out.is_empty() { "_comp".into() } else { out }
}

fn is_ident_char(ch: char) -> bool {
    ch.is_ascii_alphanumeric() || ch == '_'
}

/// Escape content for use in r#"..."# raw string literals.
/// The sequence "# would terminate the raw string early, so we escape it.
fn escape_raw_string(s: &str) -> String {
    s.replace("\"#", "\"\\#")
}
